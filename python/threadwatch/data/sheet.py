"""Build docs/data.md and one plot per dataset from the files actually on disk.

Sizes, rates, sampling and licences are read from the converted series and the downloaded
licence files, not typed by hand. Run: python -m threadwatch.data sheet
"""
from __future__ import annotations

import json
import pathlib

import numpy as np

from .loader import DATA_ROOT, list_series, load_series, release

_REPO = pathlib.Path(__file__).resolve().parents[3]
RAW = _REPO / "data" / "raw"
RED, BLUE, GREY = "#B91C1C", "#1D4ED8", "#6B7280"


def _licence(path):
    p = pathlib.Path(path)
    if not p.exists():
        return "licence file not found locally (check the dataset page)"
    text = p.read_text(errors="replace")
    lines = [l.strip() for l in text.splitlines() if l.strip()]
    kind = "MIT licence" if "MIT License" in text else (
        "MIT-style permission notice" if "Permission is hereby granted, free of charge" in text else "see file")
    return f"{kind} ({lines[0]})"


def _stats(root, prefix):
    rows = []
    for name in list_series(root, prefix):
        x, y, m = load_series(name, root)
        rows.append({"name": name, "n": m["n"], "rate": float(np.mean(y)), "meta": m,
                     "bytes": m["n"] * 5})
        release(x, y)
    return rows


def _plot(root, name, out, lo=None, hi=None, title=None):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    x, y, m = load_series(name, root)
    if lo is None:
        first = int(np.argmax(y)) if y.any() else 0
        lo = max(0, first - 400)
        hi = min(len(x), lo + 2000)
    xs, ys = np.array(x[lo:hi]), np.array(y[lo:hi])
    release(x, y)
    fig, ax = plt.subplots(figsize=(8, 2.6), dpi=150)
    ax.plot(np.arange(lo, hi), xs, lw=0.8, color=BLUE)
    ax.fill_between(np.arange(lo, hi), xs.min(), xs.max(), where=ys > 0, color=RED, alpha=0.18,
                    label="labelled anomaly")
    ax.set(xlabel="sample index", ylabel="value", title=title or name)
    ax.legend(loc="upper right", frameon=False)
    ax.grid(alpha=0.25)
    fig.tight_layout()
    fig.savefig(out)
    plt.close(fig)


def build(root=DATA_ROOT, raw=RAW, docs=_REPO / "docs"):
    docs = pathlib.Path(docs)
    (docs / "figures").mkdir(parents=True, exist_ok=True)
    nab, smd, syn = _stats(root, "nab_"), _stats(root, "smd_"), _stats(root, "syn_")
    L = ["# Data sheet", "",
         "Generated by `python -m threadwatch.data sheet` from the files in `data/series/`. "
         "Sizes, rates and sampling intervals are measured; licences are quoted from the downloaded "
         "licence files. Format: `.f32` (little-endian float32) + `.labels.u8` + `.json`.", ""]

    def block(title, rows, lic, fig, extra):
        n_tot = sum(r["n"] for r in rows)
        rates = [r["rate"] for r in rows]
        samp = sorted({str(r["meta"].get("sampling")) for r in rows})
        miss = sum(r["meta"].get("n_missing_filled", 0) or 0 for r in rows)
        L.extend([f"## {title}", "",
                  "| Item | Value |", "|---|---|",
                  f"| Source | {rows[0]['meta']['source'].split(' ')[0] if rows else '-'} |",
                  f"| Series | {len(rows)} |", f"| Total samples | {n_tot:,} |",
                  f"| Samples per series | min {min(r['n'] for r in rows):,} / max {max(r['n'] for r in rows):,} |",
                  f"| Sampling interval | {', '.join(samp)} |",
                  f"| Anomaly rate | mean {100*np.mean(rates):.2f}% (min {100*min(rates):.2f}%, max {100*max(rates):.2f}%) |",
                  f"| Missing values forward-filled | {miss} |",
                  f"| Disk size (f32 + labels) | {sum(r['bytes'] for r in rows)/1e6:.1f} MB |",
                  f"| Licence | {lic} |", ""])
        L.extend(extra)
        L.extend([f"![{title}](figures/{fig})", ""])

    if nab:
        block("NAB (AWS CloudWatch)", nab, _licence(raw / "NAB" / "LICENSE.txt"), "data-nab.png", [
            "Labels: NAB provides anomaly windows (start, end) per file; a sample is labelled 1 if its "
            "timestamp lies inside a window, bounds included. Selection: all files of `realAWSCloudwatch/`. "
            + (f"Series without any labelled window (F1 undefined, kept for timing): "
               f"{', '.join(r['name'] for r in nab if r['rate'] == 0)}." if any(r['rate'] == 0 for r in nab) else ""),
            "", "These series are short (about 1.2k to 4.7k samples): they measure detection quality, not scaling.", ""])
        _plot(root, "nab_ec2_cpu_utilization_24ae8d", docs / "figures" / "data-nab.png",
              title="NAB ec2_cpu_utilization_24ae8d (anomaly window shaded)")
    if smd:
        cols = ", ".join(f"{r['name'][4:]}: {r['meta']['metric']}" for r in smd)
        block("SMD (Server Machine Dataset)", smd, _licence(raw / "OmniAnomaly" / "ServerMachineDataset" / "LICENSE"),
              "data-smd.png", [
            "Test split only (labelled). SMD has 38 unnamed metrics per machine; one metric per machine is "
            "used: the dimension appearing in the most anomaly segments of that machine's "
            "`interpretation_label` file (ties: lowest index). 0-based column used per machine:", "",
            cols, ""])
        _plot(root, "smd_machine-1-1", docs / "figures" / "data-smd.png",
              title="SMD machine-1-1 (selected metric, anomaly shaded)")
    if syn:
        block("Synthetic generator", syn, "own code (this repository)", "data-synthetic.png", [
            "Trend + daily and weekly cycles + AR(1) noise (phi 0.7) + labelled spikes, level shifts and "
            "variance bursts. Requested rate 0.1%; events are drawn until the labelled samples reach the "
            "target and never overlap. Same seed gives identical bytes. For timing only: F1 on synthetic "
            "data measures the generator, not real detection quality.", "",
            "| Name | n | seed | events | anomaly rate |", "|---|---|---|---|---|"] +
            [f"| {r['name']} | {r['n']:,} | {r['meta']['seed']} | {r['meta'].get('n_events')} | {100*r['rate']:.3f}% |"
             for r in syn] + [""])
        _plot(root, "syn_1M" if any(r["name"] == "syn_1M" for r in syn) else syn[0]["name"], docs / "figures" / "data-synthetic.png",
              title="syn_1M (zoom on first anomaly)")
    (docs / "data.md").write_text("\n".join(L))
    return docs / "data.md"
